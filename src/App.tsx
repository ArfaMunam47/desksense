import React, { useState, useEffect } from 'react';
import { TitleBar } from './components/TitleBar';
import { Navigation, NavTab } from './components/Navigation';
import { CaptureModal } from './components/CaptureModal';
import { HomeView } from './views/HomeView';
import { GuidedHelpView } from './views/GuidedHelpView';
import { TaskLibraryView } from './views/TaskLibraryView';
import { HistoryView } from './views/HistoryView';
import { SettingsView } from './views/SettingsView';
import {
  Task,
  ScreenCapture,
  GuidanceStep,
  ScreenAnalysisData,
  AppSettings,
  ServerStatus,
} from './types';
import { VERIFIED_TASKS } from './data/taskLibrary';
import { getServerStatus, analyzeScreen, askAssistant } from './services/api';
import {
  loadSettings,
  saveSettings,
  addHistoryItem,
  clearAllHistory,
  DEFAULT_SETTINGS,
} from './services/storage';

export default function App() {
  const [currentTab, setCurrentTab] = useState<NavTab>('home');
  const [question, setQuestion] = useState<string>('');
  const [capture, setCapture] = useState<ScreenCapture | null>(null);
  const [isCaptureModalOpen, setIsCaptureModalOpen] = useState(false);
  const [analysisData, setAnalysisData] = useState<ScreenAnalysisData | null>(null);
  const [activeSteps, setActiveSteps] = useState<GuidanceStep[]>([]);
  const [currentStepIndex, setCurrentStepIndex] = useState(0);
  const [isLoading, setIsLoading] = useState(false);
  const [errorMessage, setErrorMessage] = useState<string | null>(null);
  const [serverStatus, setServerStatus] = useState<ServerStatus | null>(null);
  const [settings, setSettings] = useState<AppSettings>(loadSettings);

  // Check backend server status on mount
  const checkStatus = async () => {
    const status = await getServerStatus();
    setServerStatus(status);
  };

  useEffect(() => {
    checkStatus();
  }, []);

  // Sync settings changes to localStorage
  const handleUpdateSettings = (newSettings: AppSettings) => {
    setSettings(newSettings);
    saveSettings(newSettings);
  };

  // Dark mode class on html/body element
  useEffect(() => {
    const root = document.documentElement;
    if (settings.theme === 'dark') {
      root.classList.add('dark');
    } else if (settings.theme === 'light') {
      root.classList.remove('dark');
    } else {
      // System preference
      if (window.matchMedia('(prefers-color-scheme: dark)').matches) {
        root.classList.add('dark');
      } else {
        root.classList.remove('dark');
      }
    }
  }, [settings.theme]);

  // Check matching task library item for quick deterministic match
  const findMatchingLibraryTask = (query: string): Task | null => {
    const q = query.toLowerCase();
    for (const task of VERIFIED_TASKS) {
      if (
        task.title.toLowerCase().includes(q) ||
        q.includes(task.title.toLowerCase()) ||
        task.tags.some((tag) => q.includes(tag))
      ) {
        return task;
      }
    }
    return null;
  };

  // Launch a question into Guided Help
  const handleAskQuestion = async (userQuestion: string) => {
    setQuestion(userQuestion);
    setCurrentTab('guided');
    setErrorMessage(null);
    setCurrentStepIndex(0);

    // If an image is already attached, perform vision analysis
    if (capture) {
      await performScreenAnalysis(capture.dataUrl, userQuestion);
      return;
    }

    // Otherwise, check if it matches a verified library task
    const matchedTask = findMatchingLibraryTask(userQuestion);
    if (matchedTask) {
      setActiveSteps(matchedTask.steps);
      setAnalysisData({
        interfaceDescription: `Matched verified computer guide: "${matchedTask.title}".`,
        activeApplication: matchedTask.osContext,
        visibleElements: matchedTask.steps.map((s) => s.targetElement).filter(Boolean),
        interpretation: matchedTask.summary,
        confidence: 'high',
        confidenceReason: 'Verified step-by-step guidance from DeskSense Task Library catalog.',
        steps: matchedTask.steps,
        expectedResult: matchedTask.expectedResult,
        learningTakeaway: matchedTask.learningTakeaway,
      });
      return;
    }

    // Call server text assistant endpoint
    setIsLoading(true);
    try {
      const res = await askAssistant(userQuestion);
      if (res.success && res.data) {
        const steps = res.data.steps.map((s) => ({
          ...s,
          actionType: s.actionType || 'click',
        }));
        setActiveSteps(steps);
        setAnalysisData({
          interfaceDescription: res.data.summary,
          activeApplication: res.data.category || 'Windows Task',
          visibleElements: steps.map((s) => s.targetElement),
          interpretation: res.data.summary,
          confidence: 'high',
          confidenceReason: 'Generated by DeskSense Assistant model.',
          steps,
          expectedResult: res.data.expectedResult,
          learningTakeaway: res.data.learningTakeaway,
        });
      } else {
        // AI service unavailable or unconfigured
        setErrorMessage(
          res.error ||
            'Could not find a direct match. You can browse the Task Library for verified computer guides or attach a screenshot.'
        );
      }
    } catch (err: any) {
      setErrorMessage(err.message || 'Failed to process question.');
    } finally {
      setIsLoading(false);
    }
  };

  // Perform screen analysis with Gemini 3.8 Flash
  const performScreenAnalysis = async (imageBase64: string, q: string) => {
    setIsLoading(true);
    setErrorMessage(null);
    try {
      const res = await analyzeScreen(imageBase64, q);
      if (res.success && res.data) {
        setAnalysisData(res.data);
        setActiveSteps(res.data.steps);
        setCurrentStepIndex(0);
      } else {
        setErrorMessage(
          res.error ||
            'Screen analysis could not be completed. You can browse our verified Task Library.'
        );
      }
    } catch (err: any) {
      setErrorMessage(err.message || 'Screen analysis failed.');
    } finally {
      setIsLoading(false);
    }
  };

  // Load a verified task from Task Library or Home into the Guided Help workspace
  const handleSelectTask = (task: Task) => {
    setQuestion(task.title);
    setActiveSteps(task.steps);
    setCurrentStepIndex(0);
    setAnalysisData({
      interfaceDescription: `Verified DeskSense guide for ${task.title}.`,
      activeApplication: task.osContext,
      visibleElements: task.steps.map((s) => s.targetElement).filter(Boolean),
      interpretation: task.summary,
      confidence: 'high',
      confidenceReason: 'Verified step-by-step guidance from DeskSense Task Library catalog.',
      steps: task.steps,
      expectedResult: task.expectedResult,
      learningTakeaway: task.learningTakeaway,
    });
    setErrorMessage(null);
    setCurrentTab('guided');
  };

  // Step player navigation
  const handleNextStep = () => {
    if (currentStepIndex < activeSteps.length) {
      setCurrentStepIndex((prev) => prev + 1);
    }
  };

  const handlePrevStep = () => {
    if (currentStepIndex > 0) {
      setCurrentStepIndex((prev) => prev - 1);
    }
  };

  const handleJumpToStep = (index: number) => {
    if (index >= 0 && index <= activeSteps.length) {
      setCurrentStepIndex(index);
    }
  };

  // Task completion
  const handleCompleteTask = () => {
    if (settings.saveHistory && question) {
      addHistoryItem({
        question,
        category: analysisData?.activeApplication || 'Desktop Task',
        completedSteps: activeSteps.length,
        totalSteps: activeSteps.length,
        source: capture ? 'ai_vision' : 'task_library',
        takeaway: analysisData?.learningTakeaway,
      });
    }
    // Return to Home
    setCurrentTab('home');
    setCurrentStepIndex(0);
  };

  const handleDiscardCapture = () => {
    setCapture(null);
    if (analysisData?.confidenceReason?.includes('DeskSense Assistant model')) {
      // Keep existing text analysis if any
    } else if (capture) {
      setAnalysisData(null);
      setActiveSteps([]);
    }
  };

  const handleClearAllData = () => {
    clearAllHistory();
    setSettings(DEFAULT_SETTINGS);
    saveSettings(DEFAULT_SETTINGS);
    setCapture(null);
    setActiveSteps([]);
    setAnalysisData(null);
    setQuestion('');
  };

  // Accessibility font scaling styling
  const getFontScaleClass = () => {
    switch (settings.fontSize) {
      case 'large':
        return 'text-[17px]';
      case 'extra-large':
        return 'text-[19px]';
      case 'normal':
      default:
        return 'text-[15px]';
    }
  };

  return (
    <div
      className={`min-h-screen bg-slate-100 dark:bg-slate-950 text-slate-800 dark:text-slate-100 flex flex-col font-sans transition-colors ${getFontScaleClass()} ${
        settings.highContrast ? 'contrast-125' : ''
      }`}
    >
      {/* TitleBar resembling Windows 11 desktop shell */}
      <TitleBar
        status={serverStatus}
        onQuickCapture={() => setIsCaptureModalOpen(true)}
        hasActiveCapture={Boolean(capture)}
      />

      {/* Main App Navigation */}
      <Navigation
        currentTab={currentTab}
        onSelectTab={setCurrentTab}
        hasActiveTask={activeSteps.length > 0 && currentStepIndex < activeSteps.length}
      />

      {/* View Content */}
      <main className="grow">
        {currentTab === 'home' && (
          <HomeView
            onAskQuestion={handleAskQuestion}
            onOpenCapture={() => setIsCaptureModalOpen(true)}
            onSelectTask={handleSelectTask}
            onNavigateToTasks={() => setCurrentTab('tasks')}
            currentCapture={capture}
          />
        )}

        {currentTab === 'guided' && (
          <GuidedHelpView
            question={question}
            onUpdateQuestion={(newQ) => handleAskQuestion(newQ)}
            capture={capture}
            onOpenCapture={() => setIsCaptureModalOpen(true)}
            onDiscardCapture={handleDiscardCapture}
            analysisData={analysisData}
            activeSteps={activeSteps}
            currentStepIndex={currentStepIndex}
            isLoading={isLoading}
            errorMessage={errorMessage}
            onNextStep={handleNextStep}
            onPrevStep={handlePrevStep}
            onJumpToStep={handleJumpToStep}
            onCompleteTask={handleCompleteTask}
            onTriggerAnalysis={() => {
              if (capture && question) {
                performScreenAnalysis(capture.dataUrl, question);
              } else if (question) {
                handleAskQuestion(question);
              } else {
                setIsCaptureModalOpen(true);
              }
            }}
          />
        )}

        {currentTab === 'tasks' && (
          <TaskLibraryView onSelectTask={handleSelectTask} />
        )}

        {currentTab === 'history' && (
          <HistoryView
            onResumeQuestion={(q) => {
              handleAskQuestion(q);
            }}
          />
        )}

        {currentTab === 'settings' && (
          <SettingsView
            settings={settings}
            onUpdateSettings={handleUpdateSettings}
            serverStatus={serverStatus}
            onRefreshStatus={checkStatus}
            onClearAllData={handleClearAllData}
          />
        )}
      </main>

      {/* Screen Capture Modal Dialog */}
      <CaptureModal
        isOpen={isCaptureModalOpen}
        onClose={() => setIsCaptureModalOpen(false)}
        onCaptureComplete={(newCapture) => {
          setCapture(newCapture);
          if (question) {
            setCurrentTab('guided');
            performScreenAnalysis(newCapture.dataUrl, question);
          } else {
            setCurrentTab('guided');
          }
        }}
        currentCapture={capture}
        onDiscardCapture={handleDiscardCapture}
      />

      {/* Desktop App Status Bar */}
      <footer className="h-7 bg-white dark:bg-slate-900 border-t border-slate-200 dark:border-slate-800 px-3 text-[11px] text-slate-500 dark:text-slate-400 flex items-center justify-between select-none">
        <div className="flex items-center gap-3">
          <span>DeskSense Desktop Foundation</span>
          <span>•</span>
          <span className="text-emerald-600 dark:text-emerald-400 font-medium">
            User-Authorized Observation
          </span>
        </div>
        <div className="flex items-center gap-3">
          <span className="font-mono text-[10px]">
            {serverStatus?.platform || 'Web Environment'}
          </span>
        </div>
      </footer>
    </div>
  );
}
